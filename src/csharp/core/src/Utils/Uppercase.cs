        /// <summary>
        /// Uppercases <paramref name="value"/> with full Unicode case mapping,
        /// matching <c>String.prototype.toUpperCase</c> of the JavaScript
        /// reference.
        /// </summary>
        internal static string JsToUpperCase(string value)
        {
            var builder = new StringBuilder(value.Length);

            for (var i = 0; i < value.Length;)
            {
                var isPair = char.IsSurrogatePair(value, i);
                var codePoint = isPair ? char.ConvertToUtf32(value, i) : value[i];

                // A code point the table does not name uppercases to itself,
                // which is what the reference does too.
                builder.Append(Mappings.TryGetValue(codePoint, out var mapped)
                    ? mapped
                    : char.ConvertFromUtf32(codePoint));

                i += isPair ? 2 : 1;
            }

            return builder.ToString();
        }

