    /// </summary>
    /// <remarks>
    /// <para>
    /// <c>string.ToUpperInvariant()</c> applies only simple (1:1) case
    /// mappings, while the JavaScript reference applies full Unicode case
    /// mapping — <c>ß</c> becomes <c>SS</c>, the <c>ﬁ</c> ligature becomes
    /// <c>FI</c>, and Greek iota-subscript forms expand to two letters. The
    /// invariant culture also leaves the dotless <c>ı</c> alone where JS maps it
    /// to <c>I</c>.
    /// </para>
    /// <para>
    /// The table below is complete rather than a diff against the runtime's own
    /// mapping, so the result does not shift with the .NET version or the
    /// platform's ICU build. That matters more here than the extra lines: the
    /// initials of a seed are part of the rendered SVG, which every port has to
    /// reproduce byte for byte.
    /// </para>
